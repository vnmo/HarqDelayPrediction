close all;
clearvars;
clc;

delayTargetMs = [2 3 5 6 8 10];

SNRdb_avgRcvd = 10;
f_inverse = 3;
f = 1 / f_inverse;
k_xi = 80;

isReTxPrioritised = true;
isDetArr = false;
simLen = 1e6;

T = 1e-3;
pktLen = 8 * 108;
hvar = 1;

defaultM = 4;
defaultRtt = 3;       % slots: 1 Tx + 1 decoding + feedback
defaultQmax = 16;

rttList = [3 4 5 6]; % HARQ RTT in slots
MList = 1:4; % Maximum HARQ attempts
QmaxList = [4, 8, 16, 32]; % Maximum aggregate packet counts
resultRoot = "queueing_results_rtt3_phase_fifo";

for rttSlots = rttList

    feedbackDelay = rttSlots - 2;

    outputFolder = fullfile( ...
        resultRoot, ...
        "rtt", ...
        "rtt" + string(rttSlots));

    runQueueSensitivity( ...
        outputFolder, ...
        delayTargetMs, ...
        SNRdb_avgRcvd, ...
        f_inverse, ...
        f, ...
        k_xi, ...
        isReTxPrioritised, ...
        isDetArr, ...
        simLen, ...
        T, ...
        pktLen, ...
        hvar, ...
        defaultM, ...
        feedbackDelay, ...
        defaultQmax);
end

for M_Harq = MList

    feedbackDelay = defaultRtt - 2;

    outputFolder = fullfile( ...
        resultRoot, ...
        "max_attempts", ...
        "M" + string(M_Harq));

    runQueueSensitivity( ...
        outputFolder, ...
        delayTargetMs, ...
        SNRdb_avgRcvd, ...
        f_inverse, ...
        f, ...
        k_xi, ...
        isReTxPrioritised, ...
        isDetArr, ...
        simLen, ...
        T, ...
        pktLen, ...
        hvar, ...
        M_Harq, ...
        feedbackDelay, ...
        defaultQmax);
end

for maxQueueSize = QmaxList

    feedbackDelay = defaultRtt - 2;

    outputFolder = fullfile( ...
        resultRoot, ...
        "qmax", ...
        "Q" + string(maxQueueSize));

    runQueueSensitivity( ...
        outputFolder, ...
        delayTargetMs, ...
        SNRdb_avgRcvd, ...
        f_inverse, ...
        f, ...
        k_xi, ...
        isReTxPrioritised, ...
        isDetArr, ...
        simLen, ...
        T, ...
        pktLen, ...
        hvar, ...
        defaultM, ...
        feedbackDelay, ...
        maxQueueSize);
end


function runQueueSensitivity( ...
    outputFolder, ...
    delayTargetMs, ...
    SNRdb_avgRcvd, ...
    f_inverse, ...
    f, ...
    k_xi, ...
    isReTxPrioritised, ...
    isDetArr, ...
    simLen, ...
    T, ...
    pktLen, ...
    hvar, ...
    M_Harq, ...
    feedbackDelay, ...
    maxQueueSize)

    operatingFolder = fullfile( ...
        outputFolder, ...
        "sinr" + string(SNRdb_avgRcvd) + ...
        "_par" + string(f_inverse) + ...
        "_srs" + string(k_xi));

    if ~exist(operatingFolder, "dir")
        mkdir(operatingFolder);
    end

    [~, ~, etaMax] = parseMcs(28, 1);
    Nrb_min = ceil(pktLen / (134.16 * etaMax));

    [~, ~, etaMin] = parseMcs(0, 1);
    Nrb_max = ceil(pktLen / (134.16 * etaMin));

    NrbList = Nrb_min:Nrb_max;

    dvp_Harq_sim = zeros(length(delayTargetMs), length(NrbList));

    for nrbIter = 1:length(NrbList)

        Nrb = NrbList(nrbIter);

        etaReq = pktLen / (134 * Nrb);
        mcs = [];

        for mcsItem = 1:28
            [~, ~, eta_mcsItem] = parseMcs(mcsItem, 1);

            if eta_mcsItem >= etaReq
                mcs = mcsItem;
                break;
            end
        end

        if isempty(mcs)
            error("No feasible MCS found for Nrb = %d", Nrb);
        end

        p_Harq_all = getLenaHarqBler( ...
            simLen, ...
            mcs, ...
            SNRdb_avgRcvd, ...
            hvar, ...
            M_Harq, ...
            2, ...
            816, ...
            Nrb);

        if length(p_Harq_all) < M_Harq
            error( ...
                "PER vector has %d entries, but M_Harq is %d.", ...
                length(p_Harq_all), ...
                M_Harq);
        end

        p_Harq = p_Harq_all(1:M_Harq);

        [~, ~, totalLatency_sim, ~, numDroppedPkts] = ...
            simulate_queue_IR_cso( ...
                isReTxPrioritised, ...
                f, ...
                p_Harq, ...
                feedbackDelay, ...
                k_xi, ...
                simLen, ...
                maxQueueSize, ...
                M_Harq, ...
                isDetArr);

        for dIter = 1:length(delayTargetMs)

            delayTargetSlots = ...
                (delayTargetMs(dIter) * 1e-3) / T;

            numDelayViolations = ...
                sum(totalLatency_sim > delayTargetSlots);

            dvp_Harq_sim(dIter, nrbIter) = ...
                (numDelayViolations + numDroppedPkts) / ...
                (length(totalLatency_sim) + numDroppedPkts);
        end
    end

    for dIter = 1:length(delayTargetMs)

        writematrix( ...
            NrbList, ...
            fullfile( ...
                operatingFolder, ...
                string(delayTargetMs(dIter)) + ...
                "NRBListSimulation.csv"));

        writematrix( ...
            dvp_Harq_sim(dIter, :), ...
            fullfile( ...
                operatingFolder, ...
                string(delayTargetMs(dIter)) + ...
                "DVPListSimulation.csv"));
    end
end
