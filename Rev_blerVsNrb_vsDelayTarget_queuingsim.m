% Queueing simulation: sensitivity sweeps for RTT, M, and Qmax.
% runQueueSensitivity calls simulate_queue_IR_cso, not the Proposed DTMC.
% Outputs are *Simulation.csv under resultRoot. The analytical counterpart
% is Rev_blerVsNrb_vsDelayTarget, which saves *Theory.csv.
% k_xi is the CSP length; the simulator derives phase from its slot clock.
% Scenario settings are defined below. simLen is a slot count.
close all;
clearvars;
clc;

%% Common settings
delayTargetMs = [2 3 5 6 8 10];

SNRdb_avgRcvd = 10;
f_inverse = 3;
f = 1 / f_inverse;
k_xi = 80;

isReTxPrioritised = true;
isDetArr = false;
simLen = 1e6;

T = 1e-3;
pktLen = 8 * 108;
hvar = 1;

%% Default HARQ/queue settings
defaultM = 4;
defaultRtt = 3;       % slots: 1 Tx + 1 decoding + feedback
defaultQmax = 16;

%% Sensitivity ranges
rttList = [3 4 5 6];%[2 4 6 8 10];       % HARQ RTT in slots
MList = 1:4; %1:4;
QmaxList = [1 2 4 8 16];%[4 8 12 16];
resultRoot = "queueing_results_rtt3_phase_fifo";

%% 1. HARQ RTT sensitivity
for rttSlots = rttList

    % RTT consists of one transmission slot, one decoding slot,
    % and the feedback delay.
    feedbackDelay = rttSlots - 2;

    outputFolder = fullfile( ...
        resultRoot, ...
        "rtt", ...
        "rtt" + string(rttSlots));

    runQueueSensitivity( ...
        outputFolder, ...
        delayTargetMs, ...
        SNRdb_avgRcvd, ...
        f_inverse, ...
        f, ...
        k_xi, ...
        isReTxPrioritised, ...
        isDetArr, ...
        simLen, ...
        T, ...
        pktLen, ...
        hvar, ...
        defaultM, ...
        feedbackDelay, ...
        defaultQmax);
end

%% 2. Maximum HARQ-attempt sensitivity
for M_Harq = MList

    feedbackDelay = defaultRtt - 2;

    outputFolder = fullfile( ...
        resultRoot, ...
        "max_attempts", ...
        "M" + string(M_Harq));

    runQueueSensitivity( ...
        outputFolder, ...
        delayTargetMs, ...
        SNRdb_avgRcvd, ...
        f_inverse, ...
        f, ...
        k_xi, ...
        isReTxPrioritised, ...
        isDetArr, ...
        simLen, ...
        T, ...
        pktLen, ...
        hvar, ...
        M_Harq, ...
        feedbackDelay, ...
        defaultQmax);
end

%% 3. Qmax sensitivity
for maxQueueSize = QmaxList

    feedbackDelay = defaultRtt - 2;

    outputFolder = fullfile( ...
        resultRoot, ...
        "qmax", ...
        "Q" + string(maxQueueSize));

    runQueueSensitivity( ...
        outputFolder, ...
        delayTargetMs, ...
        SNRdb_avgRcvd, ...
        f_inverse, ...
        f, ...
        k_xi, ...
        isReTxPrioritised, ...
        isDetArr, ...
        simLen, ...
        T, ...
        pktLen, ...
        hvar, ...
        defaultM, ...
        feedbackDelay, ...
        maxQueueSize);
end


function runQueueSensitivity( ...
    outputFolder, ...
    delayTargetMs, ...
    SNRdb_avgRcvd, ...
    f_inverse, ...
    f, ...
    k_xi, ...
    isReTxPrioritised, ...
    isDetArr, ...
    simLen, ...
    T, ...
    pktLen, ...
    hvar, ...
    M_Harq, ...
    feedbackDelay, ...
    maxQueueSize)
    % Queueing-simulation helper for one sensitivity setting. The returned
    % packet latencies are compared with each configured delay target.

    %% Operating-point folder
    operatingFolder = fullfile( ...
        outputFolder, ...
        "sinr" + string(SNRdb_avgRcvd) + ...
        "_par" + string(f_inverse) + ...
        "_srs" + string(k_xi));

    if ~exist(operatingFolder, "dir")
        mkdir(operatingFolder);
    end

    %% Feasible PRB range
    [~, ~, etaMax] = parseMcs(28, 1);
    Nrb_min = ceil(pktLen / (134.16 * etaMax));

    [~, ~, etaMin] = parseMcs(0, 1);
    Nrb_max = ceil(pktLen / (134.16 * etaMin));

    NrbList = Nrb_min:Nrb_max;

    %% One row per delay target
    dvp_Harq_sim = zeros(length(delayTargetMs), length(NrbList));

    for nrbIter = 1:length(NrbList)

        Nrb = NrbList(nrbIter);

        %% Select minimum feasible MCS
        etaReq = pktLen / (134 * Nrb);
        mcs = [];

        for mcsItem = 1:28
            [~, ~, eta_mcsItem] = parseMcs(mcsItem, 1);

            if eta_mcsItem >= etaReq
                mcs = mcsItem;
                break;
            end
        end

        if isempty(mcs)
            error("No feasible MCS found for Nrb = %d", Nrb);
        end

        %% PER vector from 5G-LENA table
        p_Harq_all = getLenaHarqBler( ...
            simLen, ...
            mcs, ...
            SNRdb_avgRcvd, ...
            hvar, ...
            M_Harq, ...
            2, ...
            816, ...
            Nrb);

        if length(p_Harq_all) < M_Harq
            error( ...
                "PER vector has %d entries, but M_Harq is %d.", ...
                length(p_Harq_all), ...
                M_Harq);
        end

        p_Harq = p_Harq_all(1:M_Harq);

        %% Queue simulation
        [~, ~, totalLatency_sim, ~, numDroppedPkts] = ...
            simulate_queue_IR_cso( ...
                isReTxPrioritised, ...
                f, ...
                p_Harq, ...
                feedbackDelay, ...
                k_xi, ...
                simLen, ...
                maxQueueSize, ...
                M_Harq, ...
                isDetArr);

        %% Calculate DVP for all delay targets
        % All admitted packets are drained before return. Their latencies
        % plus admission drops cover every generated packet; discards
        % have Inf latency and violate each finite deadline.
        for dIter = 1:length(delayTargetMs)

            delayTargetSlots = ...
                (delayTargetMs(dIter) * 1e-3) / T;

            numDelayViolations = ...
                sum(totalLatency_sim > delayTargetSlots);

            dvp_Harq_sim(dIter, nrbIter) = ...
                (numDelayViolations + numDroppedPkts) / ...
                (length(totalLatency_sim) + numDroppedPkts);
        end
    end

    %% Save using the existing file convention
    for dIter = 1:length(delayTargetMs)

        writematrix( ...
            NrbList, ...
            fullfile( ...
                operatingFolder, ...
                string(delayTargetMs(dIter)) + ...
                "NRBListSimulation.csv"));

        writematrix( ...
            dvp_Harq_sim(dIter, :), ...
            fullfile( ...
                operatingFolder, ...
                string(delayTargetMs(dIter)) + ...
                "DVPListSimulation.csv"));
    end
end
